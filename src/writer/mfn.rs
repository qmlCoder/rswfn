/// Multiwfn 波函数文件(.mwfn)写入器
///
/// 输出与 [`crate::reader::MfnReader`]（以及 Multiwfn 的 mwfn 约定）兼容的文本，
/// 包含系统信息、`$Centers`、基组（`$Shell types` / `$Shell centers` /
/// `$Shell contraction degrees` / `$Primitive exponents` / `$Contraction coefficients`）
/// 以及分子轨道（`Index` / `Type` / `Sym` / `Energy` / `Occ` / `$Coeff`）。
///
/// 注意：`Nbasis` 为基函数数，`Nindbasis` 为分子轨道数；二者可以不同
/// （本项目的 π-only 波函数即 `Nindbasis < Nbasis`）。
use crate::base::Mole;
use crate::datas::consts::BOHR;
use crate::datas::elems;
use crate::writer::Writer;
use std::fmt::Write as FmtWrite;

pub struct MfnWriter {
    /// 待写出的分子（需含基组与系数）
    pub mole: Mole,
    /// 总能量（写入 E_tot）
    pub energy: f64,
}

impl MfnWriter {
    /// 创建一个空的写入器
    pub fn new() -> Self {
        Self {
            mole: Mole::new(crate::base::Atoms::new(&vec![], &vec![], &vec![]), None, None),
            energy: 0.0,
        }
    }

    /// 从分子（含基组与系数）构造写入器
    pub fn from_mole(mole: &Mole) -> Self {
        Self { mole: mole.clone(), energy: 0.0 }
    }

    /// 生成 mwfn 文本
    pub fn build(&self) -> String {
        let mole = &self.mole;
        // 系数按基组实际形式（l>=2 的形式）写出
        let form = mole.basis().int_form();
        let basis = mole.basis().unify_form(form);
        let calc_mole = Mole::new(mole.atoms.clone(), Some(basis.clone()), Some(mole.coefs().clone()));

        let cmat = calc_mole.coefs().get_cmat(form, &calc_mole);
        let (nato, nobt) = cmat.dim();
        let [nela, nelb] = calc_mole.coefs().obt_eles(&calc_mole);
        let obt_engs = &calc_mole.coefs().obt_engs;
        let obt_occs = &calc_mole.coefs().obt_occs;

        let atoms = calc_mole.atoms();
        let natm = atoms.len();
        let syms = atoms.syms();
        let xyzs = atoms.xyzs();
        let crgs = atoms.crgs();

        // 壳层信息
        let shls = &basis.shls;
        let nshell = shls.len();
        let nprims: usize = (0..nshell).map(|i| shls.get(i).alps.len()).sum();

        let mut text = String::new();
        text.push_str("# Generated by rswfn\n");
        text.push_str(&format!("Wfntype= {}\n", 0));
        text.push_str(&format!("Charge= {}\n", calc_mole.charge()));
        text.push_str(&format!("Naelec= {}\n", nela));
        text.push_str(&format!("Nbelec= {}\n", nelb));
        // E_tot 非本格式分析所需；写入传入的（模型）能量
        text.push_str(&format!("E_tot= {:.10}\n", self.energy));
        text.push_str(&format!("VT_ratio= {:.10}\n", 0.0));
        text.push_str(&format!("Ndim= {}\n", 3));
        text.push_str(&format!("Ncenter= {}\n", natm));
        text.push_str(&format!("Nbasis= {}\n", nato));
        text.push_str(&format!("Nindbasis= {}\n", nobt));
        text.push_str(&format!("Nprims= {}\n", nprims));
        text.push_str(&format!("Nshell= {}\n", nshell));
        text.push_str(&format!("Nprimshell= {}\n", nshell));

        // 原子中心：序号 名称 元素序数 核电荷 x y z（Å）
        text.push_str("$Centers\n");
        for i in 0..natm {
            let sym = &syms[i];
            let elem = elems::sym2atm(sym);
            let crg = crgs[i];
            let [x, y, z] = xyzs[i];
            text.push_str(&format!("{:>5} {:<2} {:>3} {:>10.5} {:>16.10} {:>16.10} {:>16.10}\n", i + 1, sym, elem, crg, x / BOHR, y / BOHR, z / BOHR));
        }

        // 壳层类型（正数=笛卡尔，负数=球谐；|type|=角动量）
        text.push_str("$Shell types\n");
        text.push_str(&fmt_ints(
            (0..nshell)
                .map(|i| {
                    let shl = shls.get(i);
                    if shl.form == "sph" && shl.ang > 1 { -(shl.ang as isize) } else { shl.ang as isize }
                })
                .collect(),
            10,
        ));

        // 壳层中心（1 基）
        text.push_str("$Shell centers\n");
        text.push_str(&fmt_ints((0..nshell).map(|i| shls.get(i).atm as isize + 1).collect(), 10));

        // 每个壳层的收缩度（原始函数个数）
        text.push_str("$Shell contraction degrees\n");
        text.push_str(&fmt_ints((0..nshell).map(|i| shls.get(i).alps.len() as isize).collect(), 10));

        // 原始指数（按壳层顺序）
        let alps: Vec<f64> = (0..nshell).flat_map(|i| shls.get(i).alps.clone()).collect();
        text.push_str("$Primitive exponents\n");
        text.push_str(&fmt_floats(&alps, 5));

        // 收缩系数（按壳层顺序）
        let coes: Vec<f64> = (0..nshell).flat_map(|i| shls.get(i).coes.clone()).collect();
        text.push_str("$Contraction coefficients\n");
        text.push_str(&fmt_floats(&coes, 5));

        // 分子轨道
        text.push_str("$MOs\n");
        for j in 0..nobt {
            text.push_str(&format!("Index= {}\n", j + 1));
            text.push_str("Type= Alpha\n");
            text.push_str("Sym= A\n");
            text.push_str(&format!("Energy= {:.10}\n", obt_engs[j]));
            text.push_str(&format!("Occ= {:.6}\n", obt_occs[j]));
            text.push_str("$Coeff\n");
            let col: Vec<f64> = (0..nato).map(|i| cmat[(i, j)]).collect();
            text.push_str(&fmt_floats(&col, 5));
        }
        text.push_str("$End\n");
        text
    }

    /// 保存到文件
    pub fn save(&self, path: &str) {
        let text = self.build();
        std::fs::write(path, text).expect("Unable to write file");
    }
}

impl Default for MfnWriter {
    fn default() -> Self {
        Self::new()
    }
}

impl Writer for MfnWriter {
    fn read_mole(&mut self, mole: &crate::base::Mole) {
        self.mole = mole.clone();
    }
}

/// 将整数列表按每行 `per` 个格式化（mwfn 数据块）
fn fmt_ints(nums: Vec<isize>, per: usize) -> String {
    let mut s = String::new();
    for (i, num) in nums.iter().enumerate() {
        write!(&mut s, "{:>6}", num).unwrap();
        if (i + 1) % per == 0 {
            s.push('\n');
        }
    }
    if nums.len() % per != 0 {
        s.push('\n');
    }
    s
}

/// 将浮点列表按每行 `per` 个格式化（mwfn 数据块）
fn fmt_floats(nums: &[f64], per: usize) -> String {
    let mut s = String::new();
    for (i, num) in nums.iter().enumerate() {
        write!(&mut s, "{:>18.10}", num).unwrap();
        if (i + 1) % per == 0 {
            s.push('\n');
        }
    }
    if !nums.is_empty() && nums.len() % per != 0 {
        s.push('\n');
    }
    s
}
